import json
import logging
from datetime import datetime, timezone
from typing import Dict, Any, List, Optional
from app.core.timezone import UTC_ZONEINFO
from app.services.ai_provider_service import OllamaProvider, HostedOpenWeightProvider
from app.core.config import settings
from app.schemas.analytics import AIInsightsResponse, AIInsightsRequest

logger = logging.getLogger(__name__)

ANALYTICS_AI_SYSTEM_PROMPT = """You are an objective, senior recruitment intelligence consultant for HireLens AI.
Your role is to analyze verified, deterministic aggregate recruitment analytics and produce actionable operational insights for agency leadership.

STRICT OPERATIONAL DIRECTIVES:
1. Ground every statement strictly in the supplied aggregate metrics.
2. DO NOT invent, hallucinate, or alter any numbers. All numbers must originate from the data payload.
3. DO NOT infer or mention protected personal characteristics (Age, Gender, Race, Caste, Religion, Disability).
4. No candidate personally identifiable information (PII) is included in this payload.
5. Identify bottlenecks, stage drop-offs, sourcing discrepancies, and concrete operational recommendations.
6. Return valid JSON only, conforming to the schema.

JSON Schema format:
{
  "summary": "2-3 sentences summarizing the overall recruitment operational health.",
  "key_findings": ["Factual observation 1 grounded in data", "Factual observation 2"],
  "bottlenecks": ["Observed bottleneck or drop-off point with stage name"],
  "operational_recommendations": ["Actionable recruiter/agency operational recommendation"]
}
"""


class AnalyticsAIService:
    def __init__(self):
        # Prefer hosted open-weight provider if configured, else Ollama
        if settings.HOSTED_AI_BASE_URL:
            self.provider = HostedOpenWeightProvider(
                base_url=settings.HOSTED_AI_BASE_URL,
                api_key=settings.HOSTED_AI_API_KEY,
                model_name=settings.LLM_MODEL or "meta-llama/Llama-3.1-8B-Instruct",
                timeout_seconds=15.0,
            )
        else:
            self.provider = OllamaProvider(
                base_url=settings.OLLAMA_BASE_URL,
                model_name=settings.LLM_MODEL or "qwen2.5:1.5b",
                timeout_seconds=15.0,
            )

    def generate_grounded_insights(
        self,
        analytics_payload: Dict[str, Any],
        request: Optional[AIInsightsRequest] = None,
    ) -> AIInsightsResponse:
        now = datetime.now(UTC_ZONEINFO)
        focus = request.focus_area if request else None

        # Clean payload to ensure strictly aggregate metrics (no PII)
        sanitized_payload = {
            "period": analytics_payload.get("reporting_period", {}),
            "overview": analytics_payload.get("overview", {}),
            "funnel": analytics_payload.get("funnel", {}),
            "hiring_performance": analytics_payload.get("hiring_performance", {}),
            "job_summary": {
                "total_jobs": analytics_payload.get("jobs", {}).get("total_jobs_evaluated", 0),
                "zero_applicant_jobs": analytics_payload.get("jobs", {}).get("jobs_with_zero_applications", 0),
            },
            "sources": [
                {
                    "source": s.get("source"),
                    "applications": s.get("applications_count"),
                    "hires": s.get("hires_count"),
                    "conversion_rate": s.get("conversion_rate"),
                }
                for s in analytics_payload.get("sources", {}).get("sources", [])[:5]
            ],
            "costs": analytics_payload.get("costs", {}),
            "focus_area": focus,
        }

        # Attempt AI generation if provider is operational
        is_available = False
        provider_name = "Deterministic Rule-Engine"
        try:
            is_available = self.provider.health_check()
        except Exception as e:
            logger.info("AI provider health check failed: %s", str(e))
            is_available = False

        if is_available:
            try:
                ai_result = self._call_ai_provider(sanitized_payload)
                if ai_result:
                    return AIInsightsResponse(
                        generated_at=now,
                        summary=ai_result.get("summary", ""),
                        key_findings=ai_result.get("key_findings", []),
                        bottlenecks=ai_result.get("bottlenecks", []),
                        operational_recommendations=ai_result.get("operational_recommendations", []),
                        provider_used=f"{self.provider.get_model_info().provider_name} ({self.provider.get_model_info().model_name})",
                        is_ai_available=True,
                        grounding_disclaimer=(
                            "Insights generated by AI grounded strictly in verified HireLens aggregate metrics. "
                            "No candidate PII or unverified numbers were processed."
                        ),
                    )
            except Exception as e:
                logger.warning("AI provider failed during insights generation: %s", str(e))

        # Deterministic fallback when AI is unavailable or offline
        fallback_data = self._generate_deterministic_fallback(sanitized_payload)
        return AIInsightsResponse(
            generated_at=now,
            summary=fallback_data["summary"],
            key_findings=fallback_data["key_findings"],
            bottlenecks=fallback_data["bottlenecks"],
            operational_recommendations=fallback_data["operational_recommendations"],
            provider_used="Deterministic Rule-Engine (AI offline)",
            is_ai_available=False,
            grounding_disclaimer=(
                "Insights generated deterministically from verified HireLens database records. "
                "AI provider is currently offline or unconfigured."
            ),
        )

    def _call_ai_provider(self, payload: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        import httpx
        payload_str = json.dumps(payload, default=str)
        prompt = (
            f"<AGGREGATE_ANALYTICS_PAYLOAD>\n{payload_str}\n</AGGREGATE_ANALYTICS_PAYLOAD>\n\n"
            "Analyze the above aggregate recruitment data and output the structured JSON insights:"
        )

        headers = {"Content-Type": "application/json"}
        if hasattr(self.provider, "api_key") and self.provider.api_key:
            headers["Authorization"] = f"Bearer {self.provider.api_key}"

        base_url = getattr(self.provider, "base_url", settings.OLLAMA_BASE_URL)
        model_name = getattr(self.provider, "model_name", settings.LLM_MODEL or "qwen2.5:1.5b")

        with httpx.Client(timeout=15.0) as client:
            if "ollama" in base_url.lower() or not hasattr(self.provider, "api_key"):
                res = client.post(
                    f"{base_url}/api/generate",
                    json={
                        "model": model_name,
                        "system": ANALYTICS_AI_SYSTEM_PROMPT,
                        "prompt": prompt,
                        "stream": False,
                        "format": "json",
                        "options": {"temperature": 0.0},
                    },
                )
                if res.status_code == 200:
                    raw = res.json().get("response", "")
                    return self.provider._sanitize_and_parse_json(raw)
            else:
                res = client.post(
                    f"{base_url}/chat/completions",
                    headers=headers,
                    json={
                        "model": model_name,
                        "messages": [
                            {"role": "system", "content": ANALYTICS_AI_SYSTEM_PROMPT},
                            {"role": "user", "content": prompt},
                        ],
                        "temperature": 0.0,
                        "response_format": {"type": "json_object"},
                    },
                )
                if res.status_code == 200:
                    raw = res.json()["choices"][0]["message"]["content"]
                    return self.provider._sanitize_and_parse_json(raw)
        return None

    def _generate_deterministic_fallback(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Grounded rule-based insight generator when external LLM is offline."""
        overview = payload.get("overview", {})
        funnel = payload.get("funnel", {})
        hiring = payload.get("hiring_performance", {})
        jobs = payload.get("job_summary", {})
        sources = payload.get("sources", [])
        costs = payload.get("costs", {})

        apps_period = overview.get("applications_in_period", 0)
        hires = overview.get("successful_hires", 0)
        active_apps = overview.get("active_applications", 0)
        completed_interviews = overview.get("interviews_completed", 0)

        tth_avg = hiring.get("time_to_hire", {}).get("average_days")
        zero_applicant_jobs = jobs.get("zero_applicant_jobs", 0)

        # 1. Summary
        if apps_period == 0 and hires == 0:
            summary = (
                f"During this reporting period, recruitment activity was minimal with 0 applications received "
                f"and {overview.get('total_active_jobs', 0)} active jobs. Focus should be directed on job distribution and sourcing."
            )
        else:
            summary = (
                f"Recruitment pipeline recorded {apps_period} applications and {hires} successful hires "
                f"with {active_apps} active candidates progressing. {completed_interviews} interviews were conducted."
            )

        # 2. Key findings
        findings = []
        if apps_period > 0:
            conv_rate = round((hires / apps_period) * 100, 2)
            findings.append(f"Application-to-hire conversion rate across evaluated jobs is {conv_rate}%.")
        if tth_avg is not None:
            findings.append(f"Average time-to-hire for completed journeys is {tth_avg} calendar days.")
        if sources:
            top_src = sources[0]
            findings.append(f"Primary candidate volume originated from '{top_src['source']}' with {top_src['applications']} applications.")
        if not findings:
            findings.append("No historical pipeline activity recorded within this selected date window.")

        # 3. Bottlenecks
        bottlenecks = []
        if zero_applicant_jobs > 0:
            bottlenecks.append(f"{zero_applicant_jobs} active job requisition(s) currently have zero applications.")
        
        stages = funnel.get("stages", [])
        for st in stages:
            drop = st.get("drop_off_count", 0)
            if drop > 0:
                bottlenecks.append(f"Stage '{st.get('label')}' experienced {drop} candidate drop-offs (rejections or withdrawals).")

        if not bottlenecks:
            bottlenecks.append("No immediate pipeline bottlenecks detected from current stage transition logs.")

        # 4. Operational recommendations
        recommendations = []
        if zero_applicant_jobs > 0:
            recommendations.append("Review job descriptions and boost outbound sourcing for job postings with 0 applicants.")
        if completed_interviews > 0 and hires == 0:
            recommendations.append("Evaluate interviewer feedback criteria to align interview rubrics with candidate conversion.")
        if costs.get("has_cost_data", False):
            recommendations.append("Track cost-per-hire per channel to allocate recruiting spend towards high-converting sources.")
        else:
            recommendations.append("Log recruitment expenses (job ads, platforms, agency fees) to enable automated cost-per-hire analytics.")

        return {
            "summary": summary,
            "key_findings": findings[:4],
            "bottlenecks": bottlenecks[:3],
            "operational_recommendations": recommendations[:3],
        }
